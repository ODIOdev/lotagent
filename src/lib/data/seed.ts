function purchase(
  id: string,
  worksheetId: string,
  status: PurchaseStatus,
  actuals: {
    winningBid: number;
    auctionFees: number;
    transportation: number;
    repairs: number;
    reconditioning: number;
    listedPrice?: number;
    soldPrice?: number;
    saleDate?: string | null;
  },
  createdAt: string,
) {
  const total =
    actuals.winningBid +
    actuals.auctionFees +
    actuals.transportation +
    actuals.repairs +
    actuals.reconditioning;
  return {
    id,
    worksheetId,
    status,
    actuals: {
      winningBid: actuals.winningBid,
      auctionFees: actuals.auctionFees,
      transportation: actuals.transportation,
      repairs: actuals.repairs,
      reconditioning: actuals.reconditioning,
      totalCost: total,
      listedPrice: actuals.listedPrice ?? 0,
      soldPrice: actuals.soldPrice ?? 0,
      saleDate: actuals.saleDate ?? null,
    },
    createdAt,
    updatedAt: createdAt,
  };
}

