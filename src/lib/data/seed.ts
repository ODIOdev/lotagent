function flags(...selected: ConditionFlagId[]): ConditionItem[] {
  return CONDITION_FLAGS.map((flag) => ({
    flag,
    selected: selected.includes(flag),
    dollarAdjustment: selected.includes(flag) ? defaultAdjustment(flag) : 0,
  }));
}

function defaultAdjustment(flag: ConditionFlagId): number {
  const map: Partial<Record<ConditionFlagId, number>> = {
    does_not_run: 1800,
    structural_damage: 2500,
    salvage_title: 1500,
    flood_concern: 2200,
    mechanical_issue: 900,
    accident_history: 600,
    rebuilt_title: 800,
    missing_keys: 250,
    warning_lights: 350,
    tire_replacement: 400,
    brake_replacement: 350,
    body_damage: 750,
    interior_damage: 400,
    rough: 500,
    unknown_condition: 300,
  };
  return map[flag] ?? 0;
}

function values(partial: Partial<VehicleValues> & Pick<VehicleValues, "wholesale" | "retail">): VehicleValues {
  const wholesale = partial.wholesale;
  const retail = partial.retail;
  return {
    tradeIn: partial.tradeIn ?? Math.round(wholesale * 0.86),
    wholesale,
    retail,
    quickSale: partial.quickSale ?? Math.round(wholesale * 0.94),
    localMarketAverage: partial.localMarketAverage ?? Math.round((wholesale + retail) / 2),
    lowMarket: partial.lowMarket ?? Math.round(wholesale * 0.9),
    highMarket: partial.highMarket ?? Math.round(retail * 1.06),
    source: partial.source ?? "Demo valuation (manual / mock adapter)",
    retrievedAt: partial.retrievedAt ?? "2026-08-28T14:00:00.000Z",
    confidence: partial.confidence ?? 72,
    manualOverride: partial.manualOverride ?? false,
    notes: partial.notes ?? "Demo figures. Connect a licensed valuation provider in Settings.",
  };
}

function applyFees(auctionKey: string, bid: number, extra: Partial<AcquisitionCosts> = {}): AcquisitionCosts {
  const schedule = FEE_PRESETS.find((item) => item.auctionKey === auctionKey) ?? FEE_PRESETS[0];
  const fees = calculateAuctionFees(schedule, bid);
  return {
    currentBid: extra.currentBid ?? bid,
    expectedWinningBid: bid,
    auctionBuyerFee: extra.auctionBuyerFee ?? fees.buyerFee,
    internetBiddingFee: extra.internetBiddingFee ?? fees.internetFee,
    gateFee: extra.gateFee ?? fees.gateFee,
    titleFee: extra.titleFee ?? fees.titleFee,
    documentationFee: extra.documentationFee ?? fees.documentationFee,
    salesTax: extra.salesTax ?? fees.tax,
    transportation: extra.transportation ?? 650,
    mechanicalRepairs: extra.mechanicalRepairs ?? 0,
    bodyRepairs: extra.bodyRepairs ?? 0,
    tires: extra.tires ?? 0,
    brakes: extra.brakes ?? 0,
    detailing: extra.detailing ?? 175,
    reconditioning: extra.reconditioning ?? 250,
    inspection: extra.inspection ?? 125,
    keys: extra.keys ?? 0,
    fuel: extra.fuel ?? 40,
    storage: extra.storage ?? 0,
    floorPlanFees: extra.floorPlanFees ?? 75,
    financingInterest: extra.financingInterest ?? 40,
    riskReserve: extra.riskReserve ?? 250,
    otherCosts: extra.otherCosts ?? 0,
    customRows: extra.customRows ?? [],
    feeOverride: extra.feeOverride ?? false,
  };
}

function sheet(input: {
  id: string;
  status: WorksheetStatus;
  assignedBuyer?: string;
  vehicle: VehicleInfo;
  condition: ConditionItem[];
  values: VehicleValues;
  costs: AcquisitionCosts;
  profit: Partial<ProfitTargets> & Pick<ProfitTargets, "expectedSellingPrice">;
  createdAt: string;
}): Worksheet {
  return {
    id: input.id,
    vehicle: input.vehicle,
    conditionItems: input.condition,
    values: input.values,
    costs: input.costs,
    profitTargets: {
      expectedSellingPrice: input.profit.expectedSellingPrice,
      desiredMinProfit: input.profit.desiredMinProfit ?? 1500,
      desiredRoi: input.profit.desiredRoi ?? 12,
      expectedHoldingPeriod: input.profit.expectedHoldingPeriod ?? 21,
      estimatedDaysToSell: input.profit.estimatedDaysToSell ?? 18,
      salesCommission: input.profit.salesCommission ?? 200,
      advertisingCost: input.profit.advertisingCost ?? 125,
      negotiationDiscount: input.profit.negotiationDiscount ?? 250,
    },
    assignedBuyer: input.assignedBuyer ?? "Jordan Hale",
    status: input.status,
    createdAt: input.createdAt,
    updatedAt: input.createdAt,
  };
}

