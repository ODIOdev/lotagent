const ALIAS: Record<string, string> = {
  chevy: "chevrolet",
  chev: "chevrolet",
  vw: "volkswagen",
  benz: "mercedesbenz",
  mercedesbenz: "mercedesbenz",
  rolls: "rollsroyce",
  rover: "landrover",
  range: "landrover",
};

export function norm(name: string) {
  return name.toLowerCase().replace(/[^a-z0-9]/g, "");
}

export function isUsRetailMake(name: string) {
  const key = ALIAS[norm(name)] ?? norm(name);
  return US_MAKES.has(key);
}
